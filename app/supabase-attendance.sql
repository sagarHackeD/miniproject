create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  uid text not null,
  staff_name text not null,
  device_id text not null,
  action text not null check (action in ('IN', 'OUT')),
  "timestamp" timestamptz not null default now()
);

alter table public.attendance
  add column if not exists staff_name text;

alter table public.attendance enable row level security;

grant insert on table public.attendance to anon;
grant select on table public.attendance to anon;

do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'attendance'
      and policyname = 'attendance_device_insert'
  ) then
    create policy attendance_device_insert
      on public.attendance
      for insert
      to anon
      with check (true);
  end if;
end;
$$;

drop policy if exists attendance_dashboard_read on public.attendance;

create policy attendance_dashboard_read
  on public.attendance
  for select
  to anon
  using (true);

create index if not exists attendance_timestamp_id_idx
  on public.attendance ("timestamp" desc, id desc);

create index if not exists attendance_uid_timestamp_id_idx
  on public.attendance (uid, "timestamp" desc, id desc);

create or replace function public.get_attendance_dashboard(
  p_start_date date,
  p_end_date date,
  p_timezone text
)
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $function$
declare
  v_start timestamptz;
  v_end timestamptz;
  v_dashboard jsonb;
begin
  if p_start_date is null or p_end_date is null or p_end_date < p_start_date then
    raise exception 'Invalid attendance date range.' using errcode = '22023';
  end if;

  if p_timezone is null or not exists (
    select 1
    from pg_catalog.pg_timezone_names
    where name = p_timezone
  ) then
    raise exception 'Invalid attendance time zone.' using errcode = '22023';
  end if;

  v_start := p_start_date::timestamp at time zone p_timezone;
  v_end := (p_end_date + 1)::timestamp at time zone p_timezone;

  with scoped as (
    select
      a.id,
      a.uid,
      a.staff_name,
      a.device_id,
      a.action,
      a."timestamp",
      (a."timestamp" at time zone p_timezone)::date as local_day
    from public.attendance as a
    where a."timestamp" >= v_start
      and a."timestamp" < v_end
  ),
  daily_counts as (
    select
      s.local_day,
      count(*)::integer as scans,
      count(distinct s.uid)::integer as staff_count
    from scoped as s
    group by s.local_day
  ),
  staff_counts as (
    select
      s.uid,
      coalesce((array_agg(s.staff_name order by s."timestamp" desc, s.id desc))[1], s.uid) as staff_name,
      count(distinct s.local_day)::integer as days_present,
      count(*)::integer as scans,
      min(s."timestamp") filter (where s.action = 'IN') as first_in,
      max(s."timestamp") filter (where s.action = 'OUT') as last_out,
      (array_agg(s.action order by s."timestamp" desc, s.id desc))[1] as last_action,
      max(s."timestamp") as last_scan
    from scoped as s
    group by s.uid
  )
  select jsonb_build_object(
    'summary', jsonb_build_object(
      'checked_in_now', (
        select count(*)::integer
        from (
          select distinct on (a.uid) a.action
          from public.attendance as a
          order by a.uid, a."timestamp" desc, a.id desc
        ) as latest
        where latest.action = 'IN'
      ),
      'scans_in_range', (select count(*)::integer from scoped),
      'staff_in_range', (select count(distinct s.uid)::integer from scoped as s)
    ),
    'daily', coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            'date', days.day::date,
            'scans', coalesce(counts.scans, 0),
            'staff_count', coalesce(counts.staff_count, 0)
          )
          order by days.day
        )
        from generate_series(
          p_start_date::timestamp,
          p_end_date::timestamp,
          interval '1 day'
        ) as days(day)
        left join daily_counts as counts on counts.local_day = days.day::date
      ),
      '[]'::jsonb
    ),
    'staff', coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            'uid', s.uid,
            'staff_name', s.staff_name,
            'days_present', s.days_present,
            'scans', s.scans,
            'first_in', s.first_in,
            'last_out', s.last_out,
            'last_action', s.last_action,
            'last_scan', s.last_scan
          )
          order by s.staff_name, s.uid
        )
        from staff_counts as s
      ),
      '[]'::jsonb
    ),
    'records', coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            'id', recent.id,
            'uid', recent.uid,
            'staff_name', coalesce(recent.staff_name, recent.uid),
            'device_id', recent.device_id,
            'action', recent.action,
            'timestamp', recent."timestamp"
          )
          order by recent."timestamp" desc, recent.id desc
        )
        from (
          select a.id, a.uid, a.staff_name, a.device_id, a.action, a."timestamp"
          from public.attendance as a
          order by a."timestamp" desc, a.id desc
          limit 500
        ) as recent
      ),
      '[]'::jsonb
    )
  )
  into v_dashboard;

  return v_dashboard;
end;
$function$;

revoke all on function public.get_attendance_dashboard(date, date, text) from public;
grant execute on function public.get_attendance_dashboard(date, date, text) to anon;

